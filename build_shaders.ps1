# Compiles src\shaders\*.hlsl into the headers the add-on embeds:
#   gtao.hlsl -> gtao_blob.h (kGtaoPs), shadow.hlsl -> shadow_blobs.h (kShadowPs, kShadowFadePs).
# Needs the Windows SDK's fxc.exe (Direct3D 11, ps_5_0). The generated headers are
# committed, so build.ps1 works without the SDK.
$ErrorActionPreference = 'Stop'
$root = $PSScriptRoot

$fxc = (Get-Command fxc.exe -ErrorAction SilentlyContinue).Source
if (-not $fxc) {
    $fxc = Get-ChildItem "${env:ProgramFiles(x86)}\Windows Kits\10\bin\*\x64\fxc.exe" -ErrorAction SilentlyContinue |
        Sort-Object FullName -Descending | Select-Object -First 1 -ExpandProperty FullName
}
if (-not $fxc) { throw "fxc.exe not found (Windows SDK). Install the Windows 10/11 SDK." }
New-Item -ItemType Directory -Force "$root\bin\shaders" | Out-Null

# Compiles each variant (name, defines) of one source into one header of byte arrays.
function Build-Header($source, $header, $variants) {
    $out = New-Object System.Text.StringBuilder
    [void]$out.AppendLine("// Generated by build_shaders.ps1 from $source - do not edit.")
    [void]$out.AppendLine('#pragma once')
    [void]$out.AppendLine('#include <cstdint>')
    foreach ($v in $variants) {
        $name, $defines = $v
        $file = "$root\bin\shaders\$name.dxbc"
        $args = @('/nologo', '/T', 'ps_5_0', '/E', 'main', '/O3') + ($defines | ForEach-Object { "/D$_" })
        & $fxc @args /Fo $file "$root\src\shaders\$source" | Out-Null
        if ($LASTEXITCODE) { throw "shader compile failed: $name" }
        $bytes = [System.IO.File]::ReadAllBytes($file)
        [void]$out.AppendLine("alignas(4) static const uint8_t k$name[$($bytes.Length)] = {")
        for ($i = 0; $i -lt $bytes.Length; $i += 24) {
            $line = ($bytes[$i..([Math]::Min($i + 23, $bytes.Length - 1))] | ForEach-Object { '0x{0:x2}' -f $_ }) -join ','
            [void]$out.AppendLine("    $line,")
        }
        [void]$out.AppendLine('};')
        Write-Host "  $name ($($bytes.Length) bytes)"
    }
    [System.IO.File]::WriteAllText("$root\src\shaders\$header", $out.ToString())
    Write-Host "Wrote $root\src\shaders\$header"
}

Build-Header 'gtao.hlsl' 'gtao_blob.h' @(, @('GtaoPs', @()))
Build-Header 'shadow.hlsl' 'shadow_blobs.h' @(@('ShadowPs', @('USE_FADE_PLANE=0')), @('ShadowFadePs', @('USE_FADE_PLANE=1')))
